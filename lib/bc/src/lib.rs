    #[derive(Default)]
    struct Kept {
        written: Vec<u8>,
        said: String,
    }

    impl run::World for Kept {
        fn write(&mut self, bytes: &[u8]) {
            self.written.extend_from_slice(bytes);
        }

        fn say(&mut self, text: &str) {
            self.said.push_str(text);
        }
    }

    /// A run with the library read, as -l has it.
    fn with_library() -> (run::Bc, Kept) {
        let mut bc = run::Bc::new();
        let mut kept = Kept::default();
        bc.begin("library");
        bc.feed(LIBRARY.as_bytes(), &mut kept);
        bc.end(&mut kept);
        bc.set_scale(20);
        bc.begin("-");
        (bc, kept)
    }

    /// The line `program` writes, its breaks taken out.
    fn line(bc: &mut run::Bc, kept: &mut Kept, program: &str) -> String {
        kept.written.clear();
        bc.feed(program.as_bytes(), kept);
        String::from_utf8_lossy(&kept.written).replace("\\\n", "")
    }

