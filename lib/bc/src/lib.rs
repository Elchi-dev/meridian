    #[test]
    fn the_library_gives_true_values_cut_to_their_scale() {
        let (mut bc, mut kept) = with_library();
        assert_eq!(kept.said, "", "the library reads without a mistake");
        for (expr, scale, wanted) in TRUE {
            let got = line(
                &mut bc,
                &mut kept,
                &alloc::format!("scale = {scale}; {expr}\n"),
            );
            assert_eq!(got, alloc::format!("{wanted}\n"), "{expr} at {scale}");
        }
        assert_eq!(kept.said, "");
    }

    #[test]
    fn the_library_answers_its_edges_as_gnu_bc_does() {
        let (mut bc, mut kept) = with_library();
        for (expr, wanted) in [
            ("l(0)", "-99999999999999999999.00000000000000000000"),
            ("l(-1)", "-99999999999999999999.00000000000000000000"),
            ("l(1)", "0"),
            ("e(0)", "1.00000000000000000000"),
            ("e(-1)", ".36787944117144232159"),
            (
                "e(100)",
                "26881171418161354484126255515800135873611118.77374192241519160861",
            ),
            ("s(0)", "0"),
            ("c(0)", "1.00000000000000000000"),
            ("a(0)", "0"),
            ("a(10^30)", "1.57079632679489661923"),
            ("j(0, 0)", "1.00000000000000000000"),
            ("j(1, 0)", "0"),
            ("j(-1, 2)", "-.57672480775687338720"),
            ("j(2.7, 1)", ".11490348493190048046"),
            ("scale", "20"),
        ] {
            assert_eq!(
                line(&mut bc, &mut kept, &alloc::format!("{expr}\n")),
                alloc::format!("{wanted}\n"),
                "{expr}"
            );
        }
        assert_eq!(
            line(&mut bc, &mut kept, "scale = 0; e(1); l(0)\n"),
            "2\n0\n"
        );
        assert_eq!(
            line(&mut bc, &mut kept, "scale = 20; s(10^30)\n"),
            "-.09011690191213805803\n",
            "where GNU's says .27129181675669665974, not taking out all of the turns"
        );
        assert_eq!(kept.said, "");
    }

    #[test]
    fn a_program_may_define_the_library_s_names_anew() {
        let (mut bc, mut kept) = with_library();
        assert_eq!(
            line(&mut bc, &mut kept, "define e(x) { return (x + 1) }\ne(1)\n"),
            "2\n"
        );
        assert_eq!(
            line(&mut bc, &mut kept, "scale = 5; l(e(1))\n"),
            ".69314\n",
            "the others stay"
        );
        assert_eq!(
            line(&mut bc, &mut kept, "define a(x) { return (0) }\ns(1)\n"),
            "",
            "and their own calls reach the new one, as names do in bc"
        );
        assert_eq!(kept.said, "bc: a division by zero\n", "a turn of 0");
    }
