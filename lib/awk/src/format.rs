    #[test]
    fn infinities_and_what_is_no_number_are_words() {
        assert_eq!(real_of("%f", f64::INFINITY), "inf");
        assert_eq!(real_of("%F", f64::INFINITY), "INF");
        assert_eq!(real_of("%e", f64::NEG_INFINITY), "-inf");
        assert_eq!(real_of("%+g", f64::INFINITY), "+inf");
        assert_eq!(real_of("%G", f64::NAN), "NAN");
        assert_eq!(real_of("%f", -f64::NAN), "nan", "no sign for no number");
        assert_eq!(
            real_of("%08f", f64::INFINITY),
            "     inf",
            "blanks, not zeros"
        );
        assert_eq!(real_of("%-6e", f64::NAN), "nan   ");
    }

    #[test]
    fn negative_numbers_under_unsigned_letters_are_two_s_complements() {
        assert_eq!(integer_of("%u", -1), "18446744073709551615");
        assert_eq!(integer_of("%x", -1), "ffffffffffffffff");
        assert_eq!(integer_of("%o", -8), "1777777777777777777770");
        assert_eq!(integer_of("%X", -255), "FFFFFFFFFFFFFF01");
        assert_eq!(integer_of("%+x", 5), "5", "a sign only for d and i");
        assert_eq!(integer_of("% u", 5), "5");
        assert_eq!(
            integer_of("%u", i128::MAX),
            "18446744073709551615",
            "what C cannot hold stays at its end"
        );
        assert_eq!(integer_of("%#o", 0), "0");
        assert_eq!(integer_of("%#o", 8), "010");
        assert_eq!(integer_of("%#.3o", 8), "010");
        assert_eq!(integer_of("%#.0o", 0), "0", "the other form keeps the zero");
        assert_eq!(integer_of("%#x", 0), "0");
    }

