//! Numbers and text as C's printf writes them, which awk's printf and
//! sprintf follow, and so do its numbers made strings with `CONVFMT` and
//! `OFMT`. The digits of a double come from `core::fmt`, which writes
//! them exactly; what is done here is C's shapes around them.

use alloc::format;
use alloc::string::String;

/// The widest field and the longest precision taken; more would only
/// fill a program's memory with blanks.
pub const MOST: usize = 4096;

/// What goes before a number that is not below zero: nothing, a `+`
/// as the `+` flag asks, or a blank as the blank flag does; `+` wins.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Sign {
    #[default]
    None,
    Plus,
    Blank,
}

/// One conversion of a printf format: its flags, width, precision and
/// letter.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Spec {
    /// `-`: the field's room after the value, not before it.
    pub left: bool,
    pub sign: Sign,
    /// `#`: the other form, a point always, or a base's prefix.
    pub alternate: bool,
    /// `0`: zeros rather than blanks in front of a number.
    pub zero: bool,
    pub width: Option<usize>,
    pub precision: Option<usize>,
    pub letter: u8,
}

/// Whether a conversion's width and precision are to be taken from the
/// values, as a `*` says.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Stars {
    pub width: bool,
    pub precision: bool,
}

/// The number the digits at the start of `text` write, at most
/// [`MOST`], and how many bytes they take.
fn digits(text: &[u8]) -> (usize, usize) {
    let len = text.iter().take_while(|b| b.is_ascii_digit()).count();
    let n = text[..len].iter().fold(0usize, |n, &b| {
        n.saturating_mul(10).saturating_add(usize::from(b - b'0'))
    });
    (n.min(MOST), len)
}

/// The conversion `text` begins with, `text` starting after its `%`:
/// the conversion, its stars, and how many bytes it takes; none when it
/// is none. Length letters such as `l`, which mean nothing to awk, are
/// passed over.
#[must_use]
pub fn parse(text: &[u8]) -> Option<(Spec, Stars, usize)> {
    let mut spec = Spec::default();
    let mut stars = Stars::default();
    let mut at = 0;
    while let Some(&byte) = text.get(at) {
        match byte {
            b'-' => spec.left = true,
            b'+' => spec.sign = Sign::Plus,
            b' ' if spec.sign == Sign::None => spec.sign = Sign::Blank,
            b' ' => {}
            b'#' => spec.alternate = true,
            b'0' => spec.zero = true,
            _ => break,
        }
        at += 1;
    }
    if text.get(at) == Some(&b'*') {
        stars.width = true;
        at += 1;
    } else {
        let (width, len) = digits(&text[at..]);
        if len > 0 {
            spec.width = Some(width);
        }
        at += len;
    }
    if text.get(at) == Some(&b'.') {
        at += 1;
        if text.get(at) == Some(&b'*') {
            stars.precision = true;
            at += 1;
        } else {
            let (precision, len) = digits(&text[at..]);
            spec.precision = Some(precision);
            at += len;
        }
    }
    while matches!(
        text.get(at),
        Some(b'h' | b'l' | b'L' | b'q' | b'j' | b'z' | b't')
    ) {
        at += 1;
    }
    let letter = *text.get(at)?;
    if !b"diouxXeEfFgGcs".contains(&letter) {
        return None;
    }
    spec.letter = letter;
    Some((spec, stars, at + 1))
}

/// What goes before a number not below zero.
fn shown(sign: Sign) -> &'static str {
    match sign {
        Sign::None => "",
        Sign::Plus => "+",
        Sign::Blank => " ",
    }
}

/// `body` after `lead`, filled out to the width `spec` asks: with zeros
/// between them when `zeros` lets the `0` flag have its way, else with
/// blanks before or after.
fn padded(spec: &Spec, lead: &str, body: &str, zeros: bool) -> String {
    let len = lead.chars().count() + body.chars().count();
    let width = spec.width.unwrap_or(0);
    if len >= width {
        return format!("{lead}{body}");
    }
    let room = width - len;
    if spec.left {
        format!("{lead}{body}{}", " ".repeat(room))
    } else if spec.zero && zeros {
        format!("{lead}{}{body}", "0".repeat(room))
    } else {
        format!("{}{lead}{body}", " ".repeat(room))
    }
}

/// `x`, which is no less than zero, with `precision` digits after the
/// point, and with `alternate` a point even when there are none.
fn fixed(x: f64, precision: usize, alternate: bool) -> String {
    let mut written = format!("{x:.precision$}");
    if alternate && precision == 0 {
        written.push('.');
    }
    written
}

/// The power of ten `x` is written with when it has `significant`
/// digits in the e form.
fn power(x: f64, significant: usize) -> i32 {
    let after = significant.saturating_sub(1);
    let written = format!("{x:.after$e}");
    written
        .split_once('e')
        .and_then(|(_, power)| power.parse().ok())
        .unwrap_or(0)
}

/// `x`, which is no less than zero, in the e form: one digit, a point
/// and `precision` digits, then the power of ten, signed and two digits
/// at least.
fn exponent(x: f64, precision: usize, alternate: bool) -> String {
    let written = format!("{x:.precision$e}");
    let (digits, _) = written.split_once('e').unwrap_or((&written, ""));
    let mut digits = String::from(digits);
    if alternate && precision == 0 {
        digits.push('.');
    }
    let power = power(x, precision + 1);
    let sign = if power < 0 { '-' } else { '+' };
    format!("{digits}e{sign}{:02}", power.unsigned_abs())
}

/// `x`, which is no less than zero, in the g form: `precision`
/// significant digits, in the f form unless its power of ten is below
/// -4 or as great as the digits, and without zeros at the end of its
/// fraction unless `alternate`.
fn general(x: f64, precision: usize, alternate: bool) -> String {
    let significant = precision.max(1);
    let power = power(x, significant);
    let most = i32::try_from(significant).unwrap_or(i32::MAX);
    let mut written = if (-4..most).contains(&power) {
        let after = usize::try_from(most - 1 - power).unwrap_or(0);
        fixed(x, after, alternate)
    } else {
        exponent(x, significant - 1, alternate)
    };
    if !alternate && written.contains('.') {
        let (digits, rest) = match written.find('e') {
            Some(e) => written.split_at(e),
            None => (written.as_str(), ""),
        };
        let digits = digits.trim_end_matches('0').trim_end_matches('.');
        written = format!("{digits}{rest}");
    }
    written
}

/// `x` as `spec` writes it with one of `e`, `E`, `f`, `F`, `g` and `G`:
/// infinities and the value that is no number as words, the rest in the
/// form the letter names.
#[must_use]
pub fn real(spec: &Spec, x: f64) -> String {
    let upper = spec.letter.is_ascii_uppercase();
    let sign = if x.is_sign_negative() && !x.is_nan() {
        "-"
    } else {
        shown(spec.sign)
    };
    if !x.is_finite() {
        let word = if x.is_nan() { "nan" } else { "inf" };
        let word = if upper {
            word.to_uppercase()
        } else {
            String::from(word)
        };
        return padded(spec, sign, &word, false);
    }
    let x = x.abs();
    let precision = spec.precision.unwrap_or(6);
    let body = match spec.letter.to_ascii_lowercase() {
        b'e' => exponent(x, precision, spec.alternate),
        b'f' => fixed(x, precision, spec.alternate),
        _ => general(x, precision, spec.alternate),
    };
    let body = if upper { body.to_uppercase() } else { body };
    padded(spec, sign, &body, true)
}

/// The whole part of `x`, as awk takes a number for an integer
/// conversion: past the integers it holds it stays at the nearest end,
/// and the value that is no number is 0.
#[must_use]
#[allow(clippy::cast_possible_truncation)]
pub fn whole(x: f64) -> i128 {
    // A cast goes toward zero, stays at the ends and takes no number as 0.
    x as i128
}

/// `n` as `spec` writes it with one of `d`, `i`, `o`, `u`, `x` and `X`.
/// The unsigned letters write a number below zero as C's do, as the 64
/// bits of its two's complement.
#[must_use]
pub fn integer(spec: &Spec, n: i128) -> String {
    let letter = spec.letter;
    let signed = matches!(letter, b'd' | b'i');
    let magnitude = if signed {
        n.unsigned_abs()
    } else if n < 0 {
        let low = i64::try_from(n).unwrap_or(i64::MIN);
        u128::from(low.cast_unsigned())
    } else {
        n.unsigned_abs().min(u128::from(u64::MAX))
    };
    let mut digits = match letter {
        b'o' => format!("{magnitude:o}"),
        b'x' => format!("{magnitude:x}"),
        b'X' => format!("{magnitude:X}"),
        _ => format!("{magnitude}"),
    };
    if let Some(precision) = spec.precision {
        if precision == 0 && magnitude == 0 {
            digits.clear();
        }
        if digits.len() < precision {
            digits = "0".repeat(precision - digits.len()) + &digits;
        }
    }
    if letter == b'o' && spec.alternate && !digits.starts_with('0') {
        digits.insert(0, '0');
    }
    let prefix = match letter {
        b'x' if spec.alternate && magnitude != 0 => "0x",
        b'X' if spec.alternate && magnitude != 0 => "0X",
        _ => "",
    };
    let sign = match (signed, n < 0) {
        (true, true) => "-",
        (true, false) => shown(spec.sign),
        _ => "",
    };
    padded(
        spec,
        &format!("{sign}{prefix}"),
        &digits,
        spec.precision.is_none(),
    )
}

/// `text` as `spec` writes it with `s`, no more of its characters than
/// the precision says, or with `c`, which the caller has cut to one.
#[must_use]
pub fn text(spec: &Spec, text: &str) -> String {
    let shown: String = match spec.precision {
        Some(precision) if spec.letter == b's' => text.chars().take(precision).collect(),
        _ => String::from(text),
    };
    padded(spec, "", &shown, false)
}

