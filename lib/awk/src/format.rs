    #[test]
    fn text_is_cut_to_its_precision_and_padded() {
        let text_of = |written: &str, s: &str| {
            let (spec, _, _) = parse(&written.as_bytes()[1..]).unwrap();
            text(&spec, s)
        };
        assert_eq!(text_of("%s", "abc"), "abc");
        assert_eq!(text_of("%.2s", "abc"), "ab");
        assert_eq!(text_of("%5s", "abc"), "  abc");
        assert_eq!(text_of("%-5s|", "abc"), "abc  ");
        assert_eq!(
            text_of("%05s", "abc"),
            "  abc",
            "blanks for text as C pads it"
        );
        assert_eq!(
            text_of("%.1s", "\u{e9}t\u{e9}"),
            "\u{e9}",
            "characters, not bytes"
        );
        assert_eq!(text_of("%3c", "x"), "  x");
        assert_eq!(text_of("%.0c", "x"), "x", "a precision cuts no character");
        assert_eq!(text_of("%4s", "\u{e9}"), "   \u{e9}");
    }

    #[test]
    fn conversions_are_read_with_their_flags_stars_and_lengths() {
        let parsed = |text: &str| parse(text.as_bytes());
        assert_eq!(
            parsed("-+#012.5ld"),
            Some((
                Spec {
                    left: true,
                    sign: Sign::Plus,
                    alternate: true,
                    zero: true,
                    width: Some(12),
                    precision: Some(5),
                    letter: b'd'
                },
                Stars::default(),
                10
            ))
        );
        assert_eq!(
            parsed(" +d").map(|p| p.0.sign),
            Some(Sign::Plus),
            "+ wins over a blank"
        );
        assert_eq!(parsed("+ d").map(|p| p.0.sign), Some(Sign::Plus));
        assert_eq!(parsed(" d").map(|p| p.0.sign), Some(Sign::Blank));
        assert_eq!(
            parsed("*.*f").map(|p| p.1),
            Some(Stars {
                width: true,
                precision: true
            })
        );
        assert_eq!(
            parsed(".f").map(|p| p.0.precision),
            Some(Some(0)),
            "a point alone is no digits"
        );
        assert_eq!(
            parsed("99999999999999999999s").map(|p| p.0.width),
            Some(Some(MOST))
        );
        assert_eq!(parsed("q"), None);
        assert_eq!(parsed("5"), None);
        assert_eq!(parsed(""), None);
        assert_eq!(parsed("hhd").map(|p| p.2), Some(3));
        assert_eq!(digits(b"12x"), (12, 2));
        assert_eq!(digits(b"x"), (0, 0));
    }
